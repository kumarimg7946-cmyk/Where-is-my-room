// Flat list of all state capitals and major cities for search and filtering
export const ALL_INDIAN_CITIES: IndianCity[] = INDIAN_STATES_DATA.flatMap(stateInfo => {
  const cities: IndianCity[] = [];
  
  // Add Capital City
  cities.push({
    name: stateInfo.capital,
    state: stateInfo.state,
    isCapital: true,
    famousHubs: `State Capital of ${stateInfo.state}, Central Universities & Govt Institutions`,
    isPopular: true
  });

  // Add Major Cities in that State
  stateInfo.majorCities.forEach(cityName => {
    // Avoid duplicate if capital is also listed in majorCities
    if (cityName.toLowerCase() !== stateInfo.capital.toLowerCase()) {
      cities.push({
        name: cityName,
        state: stateInfo.state,
        isCapital: false,
        famousHubs: `Major Education & Business Hub in ${stateInfo.state}`,
        isPopular: ['Kota', 'Pune', 'Noida', 'Gurugram', 'Indore', 'Coimbatore', 'Sikar', 'Vellore', 'Manipal', 'Kharagpur'].includes(cityName)
      });
    }
  });

  return cities;
});

// Helper functions for easy consumption across components
export const getAllIndianStates = (): string[] => {
  return INDIAN_STATES_DATA.map(s => s.state);
};

export const getStateInfo = (stateName: string): IndianStateInfo | undefined => {
  return INDIAN_STATES_DATA.find(s => s.state.toLowerCase() === stateName.toLowerCase());
};

export const getCapitalForState = (stateName: string): string => {
  const info = getStateInfo(stateName);
  return info ? info.capital : '';
};

export const getCitiesForState = (stateName: string): { capital: string; majorCities: string[]; allCities: string[] } => {
  const info = getStateInfo(stateName);
  if (!info) {
    return { capital: '', majorCities: [], allCities: [] };
  }
  const allCities = [info.capital, ...info.majorCities.filter(c => c.toLowerCase() !== info.capital.toLowerCase())];
  return {
    capital: info.capital,
    majorCities: info.majorCities,
    allCities
  };
};

export const isCapitalCity = (cityName: string, stateName?: string): boolean => {
  if (stateName) {
    const info = getStateInfo(stateName);
    return info?.capital.toLowerCase() === cityName.toLowerCase();
  }
  return INDIAN_STATES_DATA.some(s => s.capital.toLowerCase() === cityName.toLowerCase());
};
